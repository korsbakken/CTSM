def make_latlon_1d_indexed(
    ds: xr.Dataset,
    *,
    input_index_dim: str,
    output_index_dim: str | None = None,
    output_index_level_names: Mapping[CoordDim, str],
    input_index_var_names: Mapping[CoordDim, str] | None = None,
    input_multidim_index_var_name: str | None = None,
    input_multidim_index_coord_dim_name: str | None = None,
    input_multidim_index_coord_indices: Mapping[CoordDim, int] | None = None,
) -> xr.Dataset:
    """Add a coordinate index with longitude and latitude coordinates as levels
    to a Dataset that has a 1D element-based dimension and longitudes/latitudes
    either as two separate variables or as components along a coordinate
    coordinate dimension in a single variable (e.g., like `centerCoords` in ESMF
    mesh files).

    If the input Dataset has separate longitude and latitude variables, specify
    those variables in `input_index_var_names`. If the input Dataset has a
    single multidimensional variable with a coordinate dimension (e.g., like
    `centerCoords` in ESMF mesh files), specify the variable name in
    `input_multidim_index_var_name`, the name of the coordinate dimension in
    `input_multidim_index_coord_dim_name`, and which indices along that
    dimension correspond to longitude and latitude in
    `input_multidim_index_coord_indices`.

    Either `input_index_var_names` or `input_multidim_index_var_name`,
    `input_multidim_index_coord_dim_name`, and
    `input_multidim_index_coord_indices` must be specified, but only one of
    those sets.

    Parameters
    ----------
    ds : xarray.Dataset
        The input Dataset with a 1D element-based dimension.
    input_index_dim : str
        The name of the 1D element-based dimension in `ds`.
    output_index_dim : str | None, optional
        The name of the output coordinate index dimension to add to `ds`.
        Optional, defaults to `input_index_dim`.
    output_index_level_names : Mapping[CoordDim, str]
        A mapping from `CoordDim` enumeration members to the names of the levels
        in the output coordinate index that will represent longitude and
        latitude (which will then also act as coordinate variables for the
        same).
    input_index_var_names : Mapping[CoordDim, str] | None, optional
        Specify this if `ds` has a separate variable for each longitude/latitude
        coordinate. Must be a mapping from `CoordDim` enumeration members to the names of the
        longitude and latitude variables in `ds`.  Mutually exclusive with
        `input_multidim_index_var_name`. By default `None`.
    input_multidim_index_var_name : str | None, optional
        Specify this if `ds` has a single multidimensional variable with a
        coordinate dimension (e.g., like `centerCoords` in ESMF mesh files).
        The name of the variable in `ds` that contains both longitude and
        latitude coordinates along a coordinate dimension. Mutually exclusive
        with `input_index_var_names`. By default `None`.
    input_multidim_index_coord_dim_name : str | None, optional
        The name of the coordinate dimension in the variable given by
        `input_multidim_index_var_name` that separates longitude and latitude
        coordinates. Required if `input_multidim_index_var_name` is specified.
        By default `None`. Mutually exclusive with `input_index_var_names`.
    input_multidim_index_coord_indices : Mapping[CoordDim, int] | None, optional
        A mapping from `CoordDim` enumeration members to the indices along the
        coordinate dimension in the variable given by
        `input_multidim_index_var_name` that correspond to longitude and
        latitude coordinates. Required if `input_multidim_index_var_name` is
        specified. By default `None`. Mutually exclusive with
        `input_index_var_names`.

    Returns
    -------
    xarray.Dataset
        The modified Dataset with the added coordinate index.
    """
    if (
            (input_index_var_names is None)
            == (input_multidim_index_var_name is None)
    ):
        raise ValueError(
            'Either input_index_var_names or input_multidim_index_var_name '
            'must be specified, but not both.'
        )
    if output_index_dim is None:
        output_index_dim = input_index_dim

    coord_vars: dict[CoordDim, xr.DataArray]
    if input_index_var_names is not None:
        if set(input_index_var_names.keys()) != set(CoordDim):
            raise ValueError(
                'input_index_var_names must have exactly the following keys: '
                f'{set(CoordDim)}'
            )
        index_level_coords: dict[CoordDim, xr.DataArray] = {
            _coord_dim: ds[input_index_var_names[_coord_dim]]
            for _coord_dim in CoordDim
        }
    else:
        if (
                input_multidim_index_coord_dim_name is None
                or input_multidim_index_coord_indices is None
        ):
            raise ValueError(
                'If input_multidim_index_var_name is specified, both '
                'input_multidim_index_coord_dim_name and '
                'input_multidim_index_coord_indices must also be specified.'
            )
        if set(input_multidim_index_coord_indices.keys()) != set(CoordDim):
            raise ValueError(
                'input_multidim_index_coord_indices must have exactly the '
                f'following keys: {set(CoordDim)}'
            )
        index_var: xr.DataArray = ds[input_multidim_index_var_name]
        index_level_coords: dict[CoordDim, xr.DataArray] = {
            _coord_dim: index_var.isel(
                {
                    input_multidim_index_coord_dim_name:
                        input_multidim_index_coord_indices[_coord_dim]
                }
            )
            for _coord_dim in CoordDim
        }
        del index_var

    ds = ds.assign_coords(
        {
            output_index_level_names[_coord_dim]: index_level_coords[_coord_dim]
            for _coord_dim in CoordDim
        }
    )
    del index_level_coords
    ds = ds.set_index(
        {
            output_index_dim: list(output_index_level_names.values())
        }
    )
    return ds
###END def make_latlon_1d_indexed




def create_land_mask_from_landfrac(
    source_ds: xr.Dataset,
    *,
    landfrac_var_names: tp.Sequence[str] = SURFDATA_LANDFRAC_VAR_NAMES,
    landmask_var_name: str = MESH_MASK_VAR_NAME,
    landfrac_threshold: float = 0.0,
    land_mask_attrs: dict[str, tp.Any] | None = None,
) -> xr.DataArray:
    """Create a land mask DataArray from land fraction variables in a surface
    data Dataset. By default, points with land fraction values greater than 0.0
    for any listed land fraction variable are considered land. The threshold
    can be customized.

    Parameters
    ----------
    source_ds : xarray.Dataset
        The input surface data Dataset containing land fraction variables.
    landfrac_var_names : Sequence[str], optional
        The names of the land fraction variables to consider, by default
        `SURFDAT_LANDFRAC_VAR_NAMES`.
    landmask_var_name : str, optional
        The name of the output land mask variable, by default
        `MESH_MASK_VAR_NAME`.
    landfrac_threshold : float, optional
        The threshold above which a land fraction value is considered land,
        by default 0.0.
    land_mask_attrs : dict[str, Any] | None, optional
        Attributes to assign to the land mask DataArray. Optional. If
        unspecified or None, the module attribute `MESH_LAND_MASK_ATTRS` is
        used.

    Returns
    -------
    xarray.DataArray
        A DataArray representing the land mask, with 1 for points containing
        land, and 0 for ocean points.
    """
    if not isinstance(landfrac_var_names, tp.Sequence):
        raise TypeError(
            'landfrac_var_names must be a sequence of strings, '
            f'got {type(landfrac_var_names)}'
        )
    if isinstance(landfrac_var_names, str):
        landfrac_var_names = [landfrac_var_names]
    if not all(isinstance(name, str) for name in landfrac_var_names):
        raise TypeError(
            'all elements of landfrac_var_names must be strings'
        )
    mask_array: xr.DataArray = (
        source_ds[landfrac_var_names[0]] > landfrac_threshold
    )
    for var_name in landfrac_var_names[1:]:
        mask_array |= (source_ds[var_name] > landfrac_threshold)
    mask_array = mask_array.astype('int32')
    mask_array.name = landmask_var_name
    mask_array.attrs = (
        land_mask_attrs if land_mask_attrs is not None
        else MESH_LAND_MASK_ATTRS
    )
    return mask_array
###END def create_land_mask_from_landfrac


def compute_mesh_element_areas(
    mesh: xr.Dataset | Path | str,
    *,
    mesh_element_dim_name: str = MESH_ELEMENT_DIM_NAME,
    mesh_area_var_name: str = MESH_ELEMENT_AREA_VAR_NAME,
    mesh_area_attrs: dict[str, str] = MESH_ELEMENT_AREA_ATTRS,
) -> xr.DataArray:
    """Compute the area of each element in a mesh Dataset.

    Note that the function relies on creating an `esmpy.Mesh` object from file
    in order to avoid manually having to create nodes and stagger locations. As
    a result, if an `xarray.Dataset` is provided as input, it will first be
    written to a temporary netCDF file before being read by `esmpy`. The
    temporary file will be removed before returning.

    In order to avoid unnecessary imports, the `esmpy` module is only imported
    when this function is first called.

    Parameters
    ----------
    mesh_ds : xarray.Dataset
        The input mesh Dataset. Must be an ESMF mesh file.

    Returns
    -------
    xarray.DataArray
        A DataArray containing the area of each element in the mesh Dataset. The
        areas are in the units used by `esmpy.Field.get_area()` (usually
        radians^2, i.e., normalized to 4*pi). The returned data array is 1d with
        dimension given by `mesh_element_dim_name`. If `mesh` is an
        `xarray.Dataset`, the ordering of elements will match it so that the
        DataArray can be directly added to the Dataset, but note that the
        DataArray will not have any coordinates or an index. These must be added
        from the original mesh Dataset if needed.
    """
    import esmpy
    if isinstance(mesh, (str, Path)):
        mesh_obj: esmpy.Mesh = esmpy.Mesh(
            filename=str(mesh),
            filetype=esmpy.FileFormat.ESMFMESH,
        )
    else:
        with tempfile.NamedTemporaryFile(
            suffix='.nc',
            prefix='temp_mesh_',
            delete=True,
        ) as temp_mesh_file:
            mesh_path = Path(temp_mesh_file.name)
            mesh.to_netcdf(mesh_path)
            mesh_obj: esmpy.Mesh = esmpy.Mesh(
                filename=str(mesh_path),
                filetype=esmpy.FileFormat.ESMFMESH,
            )
    area_field: esmpy.Field = esmpy.Field(
        grid=mesh_obj,
        name='elementArea',
        meshloc=esmpy.MeshLoc.ELEMENT,
    )
    area_field.get_area()
    area_arr: xr.DataArray = xr.DataArray(
        data=area_field.data,
        dims=(mesh_element_dim_name,),
        attrs=mesh_area_attrs,
    )
    area_field.destroy()
    mesh_obj.destroy()
    del area_field, mesh_obj
    return area_arr
###END def compute_mesh_element_areas


def write_output_mesh_file(
    mesh_ds: xr.Dataset,
    output_path: Path|str,
    *,
    format: str | None = None,
    clobber: bool = False,
) -> None:
    """Write a modified mesh Dataset to a new netCDF file.

    Parameters
    ----------
    mesh_ds : xarray.Dataset
        The modified mesh Dataset.
    output_path : Path | str
        The path to the output netCDF file.
    format : Literal['NETCDF4', 'NETCDF4_CLASSIC', 'NETCDF3_64BIT',
            'NETCDF3_CLASSIC'] | None, optional
        The netCDF format to use for the output file. If `None`, the function
        will attempt to infer and use the format of the original mesh file if
        `mesh_ds.encoding['source']` exists. Otherwise, `NETCDF4` will be used
        by default.
    """
    if format is None:
        source_path: str | None = mesh_ds.encoding.get('source', None)
        if source_path is not None:
            try:
                with nc4.Dataset(source_path, mode='r') as src_nc4:
                    format = src_nc4.file_format
                    logger.debug(
                        f'Inferred NetCDF format "{format}" from source mesh '
                        f'file "{source_path}".'
                    )
                    if format.startswith('NETCDF3_64BIT'):
                        format = 'NETCDF3_64BIT'
            except Exception as exc:
                logger.warning(
                    f'Error when trying to open source mesh file '
                    f'"{source_path}" to infer NetCDF format. Please specify '
                    f'the format explicitly through the `format` parameter to '
                    'avoid this error, or ensure that the source file exists, '
                    'is readable, and can be read by `netCDF4.Dataset`.'
                )
        else:
            logger.warning(
                'The mesh Dataset does not specify a source file in '
                '`mesh_ds.encoding["source"]`. Using NETCDF4 by default. '
                'Specify the `format` parameter explicitly to avoid this '
                'warning.'
            )
            format = 'NETCDF4'
    if Path(output_path).exists() and not clobber:
        raise FileExistsError(
            f'Output file "{output_path}" already exists. To overwrite, set '
            'the `clobber` parameter to True.'
        )
    if format not in (
            'NETCDF4',
            'NETCDF4_CLASSIC',
            'NETCDF3_64BIT',
            'NETCDF3_CLASSIC',
    ):
        raise ValueError(
            f'Invalid NetCDF format "{format}". Must be one of '
            '"NETCDF4", "NETCDF4_CLASSIC", "NETCDF3_64BIT", or '
            '"NETCDF3_CLASSIC"'
        )
    mesh_ds.to_netcdf(
        path=output_path,
        format=format,
    )
    logger.info(f'Wrote output mesh file to "{output_path}".')
###END def write_output_mesh_file


def _get_different_name(
    name: str,
    existing_names: tp.Iterable[str],
    *,
    add_char: str = '_',
) -> str:
    """Helper function to get a name that is not in a collection of existing
    names.

    The function appends `add_char` to `name` until a name is found that is not
    in `existing_names`.

    Parameters
    ----------
    name : str
        The base name to modify if it already exists in `existing_names`.
    existing_names : Iterable[str]
        An iterable of existing names to avoid.
    add_char : str, optional
        The character to append to `name` if it already exists in
        `existing_names`, by default '_'

    Returns
    -------
    str
        A name that is not in `existing_names`, and equal to `name` if that name
        was not in `existing_names`.
    """
    new_name: str = name
    while new_name in existing_names:
        new_name += add_char
    return new_name
###END def _get_different_name


