"""Code and script to generate a mesh file land mask from the land fraction
variables in a surface data file, and add it to an existing mesh file.

The module also contains functionality to calculate the area of each element in
a mesh file. This can be helpful, since mesh files generated by
`/tools/mkmapgrids/mkscripgrid.ncl` combined with `ESMF_Scrip2Unstruct` may miss
element areas as well as the land mask. Note that this functionality currently
is restricted to regular rectangular latitude-longitude grids only.

Attributes
----------
MESH_MASK_VAR_NAME : str
    The name of the land mask variable in the output mesh file. By default
    `elementMask`.
SURFDAT_LANDFRAC_VAR_NAMES : tuple[str, ...]
    The names of the land fraction variables in the input surface data file.
    The mesh land mask will be normally be derived from points where an of the
    land fraction variables have non-zero values.
MESH_ELEMENT_AREA_VAR_NAME : str
    The name of the element area variable in the output mesh file. `elementArea`
    by default.
MESH_ELEMENT_AREA_ATTRS : dict[str, str]
    The attributes to add to the element area variable in the output mesh file.
    By default, this includes `long_name` (`"area weights"`) and `units`
    (`"radians^2"`).

Functions
---------
create_land_mask_from_landfrac(
    source_ds: xarray.Dataset,
    *,
    landfrac_var_names: Sequence[str] = SURFDAT_LANDFRAC_VAR_NAMES,
    landmask_var_name: str = MESH_MASK_VAR_NAME,
    landfrac_threshold: float = 0.0,
    land_mask_attrs: dict[str, tp.Any] | None = None,
) -> xarray.DataArray
    Create a land mask DataArray from land fraction variables in a surface data
    Dataset. By default, points with land fraction values greater than 0.0 for
    any listed land fraction variable are considered land. The threshold can be
    customized.
compute_regular_rect_element_areas(
    mesh_ds: xarray.Dataset,
    *,
    latitudes: xarray.DataArray,
    longitudes: xarray.DataArray,
) -> xarray.DataArray
write_output_mesh_file(
    mesh_ds: xarray.Dataset,
    output_path: Path,
) -> None
    Write the modified mesh Dataset to a new netCDF file.
lonlat2d_to_mesh_coords(
    lonlat_ds: xr.Dataset,
    mesh_ds: xr.Dataset,
    *,
    lon_var_name: str = 'LONGXY',
    lat_var_name: str = 'LATIXY',
    lon_dim_name: str = 'lsmlon',
    lat_dim_name: str = 'lsmlat',
    mesh_center_coords_var_name: str = 'centerCoords',
    mesh_element_dim_name: str = 'elementCount',
    mesh_coord_dim_name: str = 'coordDim',
) -> xr.Dataset
    Convert an xarray Dataset with 2D longitude and latitude dimensions to the
    1D element-based coordinate system used in a mesh Dataset.
"""
import argparse
from collections.abc import Sequence
from pathlib import Path
import typing as tp

import xarray as xr



MESH_MASK_VAR_NAME: tp.Final[str] = 'elementMask'

MESH_LAND_MASK_ATTRS: tp.Final[dict[str, tp.Any]] = {}

SURFDAT_LANDFRAC_VAR_NAMES: tp.Final[tuple[str, ...]] = (
    'LANDFRAC_PFT',
    'LANDFRAC_MKSURFDATA',
)

MESH_ELEMENT_AREA_VAR_NAME: tp.Final[str] = 'elementArea'

MESH_ELEMENT_AREA_ATTRS: tp.Final[dict[str, str]] = {
    'long_name': 'area weights',
    'units': 'radians^2',
}


def create_land_mask_from_landfrac(
    source_ds: xr.Dataset,
    *,
    landfrac_var_names: tp.Sequence[str] = SURFDAT_LANDFRAC_VAR_NAMES,
    landmask_var_name: str = MESH_MASK_VAR_NAME,
    landfrac_threshold: float = 0.0,
    land_mask_attrs: dict[str, tp.Any] | None = None,
) -> xr.DataArray:
    """Create a land mask DataArray from land fraction variables in a surface
    data Dataset. By default, points with land fraction values greater than 0.0
    for any listed land fraction variable are considered land. The threshold
    can be customized.

    Parameters
    ----------
    source_ds : xarray.Dataset
        The input surface data Dataset containing land fraction variables.
    landfrac_var_names : Sequence[str], optional
        The names of the land fraction variables to consider, by default
        `SURFDAT_LANDFRAC_VAR_NAMES`.
    landmask_var_name : str, optional
        The name of the output land mask variable, by default
        `MESH_MASK_VAR_NAME`.
    landfrac_threshold : float, optional
        The threshold above which a land fraction value is considered land,
        by default 0.0.
    land_mask_attrs : dict[str, Any] | None, optional
        Attributes to assign to the land mask DataArray. Optional. If
        unspecified or None, the module attribute `MESH_LAND_MASK_ATTRS` is
        used.

    Returns
    -------
    xarray.DataArray
        A DataArray representing the land mask, with 1 for points containing
        land, and 0 for ocean points.
    """
    STACK_DIM: str = '__STACK_DIM__'
    if not isinstance(landfrac_var_names, tp.Sequence):
        raise TypeError(
            'landfrac_var_names must be a sequence of strings, '
            f'got {type(landfrac_var_names)}'
        )
    if isinstance(landfrac_var_names, str):
        landfrac_var_names = [landfrac_var_names]
    if not all(isinstance(name, str) for name in landfrac_var_names):
        raise TypeError(
            'all elements of landfrac_var_names must be strings'
        )
    mask_array: xr.DataArray = (
        source_ds[landfrac_var_names[0]] > landfrac_threshold
    )
    for var_name in landfrac_var_names[1:]:
        mask_array |= (source_ds[var_name] > landfrac_threshold)
    mask_array = mask_array.astype('int32')
    mask_array.name = landmask_var_name
    mask_array.attrs = (
        land_mask_attrs if land_mask_attrs is not None
        else MESH_LAND_MASK_ATTRS
    )
    return mask_array
###END def create_land_mask_from_landfrac


def _get_different_name(
    name: str,
    existing_names: tp.Iterable[str],
    *,
    add_char: str = '_',
) -> str:
    """Helper function to get a name that is not in a collection of existing
    names.

    The function appends `add_char` to `name` until a name is found that is not
    in `existing_names`.

    Parameters
    ----------
    name : str
        The base name to modify if it already exists in `existing_names`.
    existing_names : Iterable[str]
        An iterable of existing names to avoid.
    add_char : str, optional
        The character to append to `name` if it already exists in
        `existing_names`, by default '_'

    Returns
    -------
    str
        A name that is not in `existing_names`, and equal to `name` if that name
        was not in `existing_names`.
    """
    new_name: str = name
    while new_name in existing_names:
        new_name += add_char
    return new_name
###END def _get_different_name


def lonlat2d_to_mesh_coords(
    lonlat_ds: xr.Dataset,
    mesh_ds: xr.Dataset,
    *,
    lon_var_name: str = 'LONGXY',
    lat_var_name: str = 'LATIXY',
    lon_dim_name: str = 'lsmlon',
    lat_dim_name: str = 'lsmlat',
    mesh_center_coords_var_name: str = 'centerCoords',
    mesh_element_dim_name: str = 'elementCount',
    mesh_coord_dim_name: str = 'coordDim',
) -> xr.Dataset:
    """Convert an xarray Dataset with 2D longitude and latitude dimensions to
    the 1D element-based coordinate system used in a mesh Dataset.

    Parameters
    ----------
    lonlat_ds : xarray.Dataset
        The input Dataset containing variables that depend on the 2D longitude
        dimensions, and variables with the longitude and latitude coordinates.
        The longitude and latitude variabbles are not required to be registered
        as coordinate variables, since that is not necessarily the case in
        surface data files.
    mesh_ds : xarray.Dataset
        A Dataset from a mesh file, which contains the dimensions and coordinate
        variables that `lonlat_ds` should be mapped to.
    lon_var_name : str, optional
        The name of the longitude variable in `lonlat_ds`, by default
        `'LONGXY'`. In general, the variable is assumed to be 2D, with
        dimensions equal to those given by both `lon_dim_name` and
        `lat_dim_name`. **NB!** The variable must contain the exact same values
        as are found in the longitude values in the mesh file variable given by
        `mesh_center_coords_var_name`.
    lat_var_name : str, optional
        The name of the latitude variable in `lonlat_ds`, by default `'LATIXY'`.
        In general, the variable is assumed to be 2D, with dimensions equal to
        those given by both `lon_dim_name` and `lat_dim_name`. **NB!** The
        variable must contain the exact same values as are found in the latitude
        values in the mesh file variable given by `mesh_center_coords_var_name`.
    lon_dim_name : str, optional
        The name of the longitude dimension in `lonlat_ds`, by default
        `'lsmlon'`.
    lat_dim_name : str, optional
        The name of the latitude dimension in `lonlat_ds`, by default
        `'lsmlat'`.
    mesh_center_coords_var_name : str, optional
        The name of the center coordinates variable in `mesh_ds`, by default
        `'centerCoords'`.
    mesh_element_dim_name : str, optional
        The name of the element dimension in `mesh_ds`, by default
        `'elementCount'`.
    mesh_coord_dim_name : str, optional
        The name of the coordinate dimension in `mesh_ds`, by default
        `'coordDim'`. This dimension is assumed to have size 2, with the first
        index representing longitude and the second index representing latitude.

    Returns
    -------
    xarray.Dataset
        A new dataset with the same variables as `lonlat_ds`, but mapped to the
        dimenions of `mesh_ds`, and with the coordinate variable given by
        `mesh_center_coords_var_name` added.
    """
    lonlat_ds_stacked: xr.Dataset = lonlat_ds.stack(
        dim={mesh_element_dim_name: (lon_dim_name, lat_dim_name)},
        create_index=False,
    )
    avoid_var_names: tp.Final[set[str]] = {
        mesh_center_coords_var_name,
        mesh_element_dim_name,
        mesh_coord_dim_name,
    }
    new_lon_var_name: str = _get_different_name(lon_var_name, avoid_var_names)
    new_lat_var_name: str = _get_different_name(lat_var_name, avoid_var_names)
    # Determine whether the lon/lat variables are already coordinates and need
    # to be reverted to regular variables at the end of the process.
    revert_coords: set[str] = set(
        _new_var_name for _new_var_name, _orig_var_name in (
            (new_lon_var_name, lon_var_name),
            (new_lat_var_name, lat_var_name),
        ) if _orig_var_name not in lonlat_ds.coords
    )
    lonlat_ds_stacked = lonlat_ds_stacked.rename_vars(
        {
            _orig_var_name: _new_var_name
            for _new_var_name, _orig_var_name in (
                (new_lon_var_name, lon_var_name),
                (new_lat_var_name, lat_var_name),
            ) if _orig_var_name != _new_var_name
        }
    )
    lonlat_ds_stacked = lonlat_ds_stacked.set_coords(
        (new_lon_var_name, new_lat_var_name)
    )