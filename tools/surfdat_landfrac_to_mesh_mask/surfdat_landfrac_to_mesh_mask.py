def lonlat2d_to_mesh_coords(
    lonlat_ds: xr.Dataset,
    mesh_ds: xr.Dataset | None = None,
    *,
    lon_var_name: str = 'LONGXY',
    lat_var_name: str = 'LATIXY',
    lon_dim_name: str = 'lsmlon',
    lat_dim_name: str = 'lsmlat',
    mesh_center_coords_var_name: str = MESH_CENTER_COORDS_VAR_NAME,
    mesh_element_dim_name: str = MESH_ELEMENT_DIM_NAME,
    mesh_coord_dim_name: str = MESH_COORD_DIM_NAME,
    keep_lon_lat_vars: bool = True,
) -> xr.Dataset:
    """Convert an xarray Dataset with 2D longitude and latitude dimensions to
    the 1D element-based coordinate system used in a mesh Dataset.

    Parameters
    ----------
    lonlat_ds : xarray.Dataset
        The input Dataset containing variables that depend on the 2D longitude
        dimensions, and variables with the longitude and latitude coordinates.
        The longitude and latitude variabbles are not required to be registered
        as coordinate variables, since that is not necessarily the case in
        surface data files.
    mesh_ds : xarray.Dataset, optional
        A Dataset from a mesh file, which contains the dimensions and coordinate
        variables that `lonlat_ds` should be mapped to. If not provided,
        `lonlat_ds` will be stacked to an element-based coordinate system as
        used in mesh files, but without aligning it to a specific mesh file.
        In order to add data from the returned Dataset to a specific mesh file,
        it must first be aligned, since the ordering of elements may differ.
    lon_var_name : str, optional
        The name of the longitude variable in `lonlat_ds`, by default
        `'LONGXY'`. In general, the variable is assumed to be 2D, with
        dimensions equal to those given by both `lon_dim_name` and
        `lat_dim_name`. **NB!** The variable must contain the exact same values
        as are found in the longitude values in the mesh file variable given by
        `mesh_center_coords_var_name`.
    lat_var_name : str, optional
        The name of the latitude variable in `lonlat_ds`, by default `'LATIXY'`.
        In general, the variable is assumed to be 2D, with dimensions equal to
        those given by both `lon_dim_name` and `lat_dim_name`. **NB!** The
        variable must contain the exact same values as are found in the latitude
        values in the mesh file variable given by `mesh_center_coords_var_name`.
    lon_dim_name : str, optional
        The name of the longitude dimension in `lonlat_ds`, by default
        `'lsmlon'`.
    lat_dim_name : str, optional
        The name of the latitude dimension in `lonlat_ds`, by default
        `'lsmlat'`.
    mesh_center_coords_var_name : str, optional
        The name of the center coordinates variable in `mesh_ds`, by default
        given by the module attribute `MESH_CENTER_COORDS_VAR_NAME`.
    mesh_element_dim_name : str, optional
        The name of the element dimension in `mesh_ds`, by default given by the
        module attribute `MESH_ELEMENT_DIM_NAME`.
    mesh_coord_dim_name : str, optional
        The name of the coordinate dimension in `mesh_ds`, by default given by
        the module attribute `MESH_COORD_DIM_NAME`. This dimension is assumed to
        have size 2, with the first index representing longitude and the second
        index representing latitude.
    keep_lon_lat_vars : bool, optional
        Whether to keep the longitude and latitude variables given by
        `lon_var_name` and `lat_var_name` in the returned Dataset. By default
        `True`. If `False`, the variables will be removed from the returned
        Dataset (but the values are retained in the variable given by
        `mesh_center_coords_var_name`).

    Returns
    -------
    xarray.Dataset
        A new dataset with the same variables as `lonlat_ds`, but mapped to the
        a 1D coordinate system as used in mesh files, and with the coordinate
        variable given by `mesh_center_coords_var_name` added. If `mesh_ds` is
        provided, the mapping will be aligned to the element ordering in
        `mesh_ds`.
    """
    if (
            mesh_center_coords_var_name in lonlat_ds.variables
            or mesh_center_coords_var_name in lonlat_ds.dims
    ):
        raise MeshCenterCoordsVarExistsError(
            var_name=mesh_center_coords_var_name
        )
    lonlat_ds_stacked: xr.Dataset = lonlat_ds.stack(
        dim={mesh_element_dim_name: (lon_dim_name, lat_dim_name)},
        create_index=False,
    )
    def _combine_attrs(
            attrs: Sequence[dict[str, str]],
            context: tp.Any,
    ) -> dict[str, str]:
        if len(attrs) != 2:
            return dict()
        if all(
            _attrs.get(_UNITS_ATTR_NAME, '').lower().startswith('degrees')
            for _attrs in attrs
        ):
            return {_UNITS_ATTR_NAME: 'degrees'}
        return dict()
    ###END def _combine_attrs
    lonlat_ds_stacked[mesh_center_coords_var_name] = xr.concat(
        [
            lonlat_ds_stacked[lon_var_name],
            lonlat_ds_stacked[lat_var_name],
        ],
        dim=mesh_coord_dim_name,
        combine_attrs=_combine_attrs,
    )
    if mesh_ds is not None:
        # Align to the mesh Dataset by reindexing according to the center
        # coordinates variable in the mesh Dataset.
        lonlat_ds_stacked = align_mesh_center_coords(
            lonlat_ds_stacked,
            align_to=mesh_ds,
            center_coords_var_name=mesh_center_coords_var_name,
        )
    if not keep_lon_lat_vars:
        lonlat_ds_stacked = lonlat_ds_stacked.drop_vars(
            (lon_var_name, lat_var_name)
        )
    return lonlat_ds_stacked
###END def lonlat2d_to_mesh_coords


def main() -> None:
    """Main function for the script to generate a mesh land mask from surface
    data.
    """
    parser = argparse.ArgumentParser(
        description=(
            'Generate a mesh land mask from land fraction variables in a '
            'surface data file, and add it t an existing mesh file.'
            '\n\nBy default also adds element areas to the mesh file (can be '
            'disabled.'
        )
    )
    parser.add_argument(
        '--mesh-file',
        type=Path,
        help='Path to the input mesh netCDF file.',
        required=True,
    )
    parser.add_argument(
        '--surfdata-file',
        type=Path,
        help='Path to the input surface data netCDF file.',
        required=True,
    )
    parser.add_argument(
        '--output-mesh-file',
        type=Path,
        help='Path to the output mesh netCDF file.',
        required=True,
    )
    parser.add_argument(
        '--surfdata-landfrac-vars',
        type=str,
        nargs='+',
        default=list(SURFDATA_LANDFRAC_VAR_NAMES),
        help='List of land fraction variable names in the surface data file '
        'to use for generating the land mask, by default '
        f'{SURFDATA_LANDFRAC_VAR_NAMES}.',
    )
    parser.add_argument(
        '--add-element-areas',
        type=bool,
        default=True,
        help='Whether to compute and add element areas to the output mesh '
        'file, by default True.',
    )
    parser.add_argument(
        '--log-level',
        type=str,
        default='INFO',
        help='Logging level, by default "INFO".',
    )

    args: argparse.Namespace = parser.parse_args()
    logging.basicConfig(level=args.log_level)
    mesh_file: Path = args.mesh_file
    output_mesh_file: Path = args.output_mesh_file
    surfdata_file: Path = args.surfdata_file
    surfdata_landfrac_vars: list[str] = args.surfdata_landfrac_vars
    mesh_mask_var_name: str = MESH_MASK_VAR_NAME
    mesh_element_area_var_name: str = MESH_ELEMENT_AREA_VAR_NAME

    logger.info(f'Opening mesh file: {mesh_file}...')
    mesh_ds: xr.Dataset = xr.open_dataset(
        mesh_file,
        cache=True,
    )

    logger.info(f'Opening and 1d-stacking surface data file: {surfdata_file}...')
    surfdata_ds: xr.Dataset = xr.open_dataset(
        surfdata_file,
        cache=True,
    )
    surfdata_ds = make_latlon_1d_indexed(
        surfdata_ds.drop_vars(
            _var for _var in surfdata_ds.data_vars.keys()
            if _var not in tuple(
                itertools.chain(
                    SURFDATA_LANDFRAC_VAR_NAMES,
                    SURFDATA_COORDS_VAR_NAMES.values()
                )
            )
        ).stack(
            dim={MESH_ELEMENT_DIM_NAME: tuple(SURFDATA_COORD_DIMS.values())},
            create_index=False,
        ),
        input_index_var_names=SURFDATA_COORDS_VAR_NAMES,
        input_index_dim=MESH_ELEMENT_DIM_NAME,
        output_index_dim=MESH_ELEMENT_DIM_NAME,
        output_index_level_names=COORD_DIM_NAMES,
    )

    logger.info(
        'Creating land mask from surface data land fraction variables...'
    )
    mesh_mask_arr: xr.DataArray = create_land_mask_from_landfrac(
        surfdata_ds,
        landfrac_var_names=surfdata_landfrac_vars,
    )

    logger.info('Indexing the mesh file dataset...')
    mesh_ds = make_latlon_1d_indexed(
        mesh_ds,
        input_index_dim=MESH_ELEMENT_DIM_NAME,
        output_index_dim=MESH_ELEMENT_DIM_NAME,
        input_multidim_index_var_name=MESH_CENTER_COORDS_VAR_NAME,
        input_multidim_index_coord_dim_name=MESH_COORD_DIM_NAME,
        input_multidim_index_coord_indices=MESH_COORD_DIMS_INDICES,
        output_index_level_names=COORD_DIM_NAMES,
    )

    logger.info(
        f'Adding land mask to mesh dataset as variable {mesh_mask_var_name}...'
    )
    if mesh_mask_var_name in mesh_ds.variables:
        logger.warning(
            f'Variable {mesh_mask_var_name} already exists in the mesh '
            'dataset and will be overwritten.'
        )
    mesh_ds[mesh_mask_var_name] = mesh_mask_arr.reindex_like(mesh_ds)
    logger.debug(
        'Adding attributes to the mesh land mask variable...',
        extra={
            'original_attrs': mesh_ds[mesh_mask_var_name].attrs,
            'new_attrs': MESH_LAND_MASK_ATTRS,
        },
    )
    mesh_ds[mesh_mask_var_name].attrs.update(MESH_LAND_MASK_ATTRS)
    del mesh_mask_arr
    surfdata_ds.close()

    if args.add_element_areas:
        logger.info(
            'Computing and adding element areas to the mesh dataset as '
            f'variable {mesh_element_area_var_name}...'
        )
        mesh_area_arr: xr.DataArray = compute_mesh_element_areas(mesh_ds)
        if mesh_element_area_var_name in mesh_ds.variables:
            logger.warning(
                f'Variable {mesh_element_area_var_name} already exists in '
                'the mesh dataset and will be overwritten.'
            )
        mesh_ds[mesh_element_area_var_name] = mesh_area_arr
        logger.debug(
            'Adding attributes to the mesh element area variable...',
            extra={
                'original_attrs': mesh_ds[mesh_element_area_var_name].attrs,
                'new_attrs': MESH_ELEMENT_AREA_ATTRS,
            },
        )
        mesh_ds[mesh_element_area_var_name].attrs.update(
            MESH_ELEMENT_AREA_ATTRS
        )
        del mesh_area_arr

    logger.info(f'Writing output mesh file: {output_mesh_file}...')
    write_output_mesh_file(
        mesh_ds,
        output_mesh_file,
    )
    mesh_ds.close()

###END def main


